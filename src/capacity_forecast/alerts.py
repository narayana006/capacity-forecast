"""Generate Prometheus alerting rules from a forecast.

Each growing resource gets one rule with a static threshold derived from its
forecast: the fraction of the limit at which, at the fitted growth rate, only
``lead_days`` of headroom remain. The rule divides the live usage query by the
live limit query, so it keeps working if the limit changes, and is narrowed to
the one resource with ``and on(<label>)``.

The output is a rules file for Prometheus (``rule_files:``) or anything that
loads the same format. Every scalar is written as a double-quoted string, which
is valid YAML, so no YAML library is needed.
"""

from __future__ import annotations

import json
import re
from collections.abc import Sequence

from .forecast import Forecast

ALERT_NAME = "CapacityForecastLowHeadroom"
GROUP_NAME = "capacity-forecast"
_PROM_DURATION = re.compile(r"^(\d+(ms|s|m|h|d|w|y))+$")
_LABEL_NAME = re.compile(r"^[a-zA-Z_][a-zA-Z0-9_]*$")


def _q(value: str) -> str:
    """A YAML double-quoted scalar (JSON string syntax is a subset of it)."""
    return json.dumps(value, ensure_ascii=False)


def _promql_string(value: str) -> str:
    """A PromQL string literal."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def threshold_ratio(forecast: Forecast, lead_days: float) -> float | None:
    """Fraction of the limit at which ``lead_days`` of headroom remain, or None if not growing."""
    growth = forecast.growth_per_day
    if growth is None or growth <= 0 or forecast.limit <= 0:
        return None
    ratio = (forecast.limit - growth * lead_days) / forecast.limit
    return max(ratio, 0.0)


def rule_expr(usage_query: str, limit_query: str, label: str, resource: str, ratio: float) -> str:
    selector = f'label_replace(vector(1), {_promql_string(label)}, {_promql_string(resource)}, "", "")'
    return (
        f"((({usage_query}) / on({label}) ({limit_query})) >= {ratio:.4f})"
        f" and on({label}) {selector}"
    )


def to_rules(
    forecasts: Sequence[Forecast],
    usage_query: str,
    limit_query: str,
    label: str,
    lead_days: float,
    for_duration: str = "1h",
    severity: str = "warning",
) -> tuple[str, int]:
    """Render a Prometheus rules file. Returns ``(text, number of rules)``.

    Resources that are flat, shrinking or have too little data get no rule and
    are listed in a comment at the top of the file.
    """
    if lead_days <= 0:
        raise ValueError("alert lead time must be positive")
    if not _PROM_DURATION.match(for_duration):
        raise ValueError(f"alert 'for' duration {for_duration!r} must look like 30m, 1h or 1h30m")
    if not label:
        raise ValueError("alert rules need --resource-label")
    if not _LABEL_NAME.match(label) or label in ("severity", "alertname"):
        raise ValueError(f"{label!r} cannot be used as the resource label in alert rules")

    rules: list[str] = []
    skipped: list[str] = []
    for f in forecasts:
        ratio = threshold_ratio(f, lead_days)
        if ratio is None:
            skipped.append(f.resource)
            continue
        pct = ratio * 100
        summary = f"{f.resource} has about {lead_days:g} days of headroom left"
        description = (
            f"Usage of {f.resource} is at or above {pct:.1f}% of its limit. At the forecast growth "
            f"of {f.growth_per_day:.4g} per day, that leaves about {lead_days:g} days before the limit. "
            "Current value: {{ $value | humanizePercentage }} of the limit."
        )
        rules.append("\n".join([
            f"      - alert: {ALERT_NAME}",
            f"        expr: {_q(rule_expr(usage_query, limit_query, label, f.resource, ratio))}",
            f"        for: {_q(for_duration)}",
            "        labels:",
            f"          severity: {_q(severity)}",
            f"          {label}: {_q(f.resource)}",
            "        annotations:",
            f"          summary: {_q(summary)}",
            f"          description: {_q(description)}",
            f"          forecast_status: {_q(f.status)}",
            f"          forecast_threshold_ratio: {_q(f'{ratio:.4f}')}",
        ]))

    header = [
        "# Generated by capacity-forecast. Static thresholds come from the forecast:",
        f"# each rule fires when about {lead_days:g} days of headroom remain at the fitted growth rate.",
        "# Regenerate after re-running the forecast; thresholds do not adapt on their own.",
    ]
    if skipped:
        header.append("# No rule (flat, shrinking or too little data): " + ", ".join(skipped))
    body = ["groups:", f"  - name: {_q(GROUP_NAME)}"]
    body.append("    rules:" if rules else "    rules: []")
    text = "\n".join(header + body + rules) + "\n"
    return text, len(rules)
